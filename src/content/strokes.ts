/** 쌍자음은 같은 자음 둘을 나란히 (왼쪽 먼저) */
const DOUBLES: Record<string, string> = { ㄲ: 'ㄱ', ㄸ: 'ㄷ', ㅃ: 'ㅂ', ㅆ: 'ㅅ', ㅉ: 'ㅈ' };

function squeeze(strokes: Stroke[], x0: number, x1: number): Stroke[] {
  return strokes.map((st) => ({ ...st, pts: st.pts.map(([x, y]) => [x0 + (x / 100) * (x1 - x0), y] as Pt) }));
}

/** 자모 하나의 획 (0~100 네모 기준). 없는 자모는 null. */
export function jamoStrokes(jamo: string): Stroke[] | null {
  if (BASE[jamo]) return BASE[jamo];
  const single = DOUBLES[jamo];
  if (single) return [...squeeze(BASE[single], 0, 48), ...squeeze(BASE[single], 52, 100)];
  return null;
}
