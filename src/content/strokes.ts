// 모양은 판정용 뼈대라서 글꼴처럼 정밀하지 않아도 된다. 음절 안 배치는 core/writing.ts가 한다.
// 겹모음(ㅘ 등)은 core/writing.ts가 두 모음 획을 나눠 놓는다. 겹받침은 아직 어휘에 없어 넣지 않았다.

export type Pt = [number, number];

export interface Stroke {
  pts: Pt[];
  /** 처음과 끝이 만나는 획 (ㅇ): 방향 판정을 하지 않는다 */
  closed?: boolean;
}

const s = (...pts: Pt[]): Stroke => ({ pts });

/** 위에서 시작해 왼쪽으로(시계 반대 방향) 도는 동그라미 */
function circle(cx: number, cy: number, rx: number, ry: number, n = 20): Stroke {
  const pts: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const t = (i / n) * Math.PI * 2;
    pts.push([Math.round((cx - rx * Math.sin(t)) * 10) / 10, Math.round((cy - ry * Math.cos(t)) * 10) / 10]);
  }
  return { pts, closed: true };
}

